/**
 * V20 多轮草稿迭代型思维链泄漏 —— 用户实测"你给我仔细说说你的屄掰开后的样子吧"
 * 结构: [草稿1] + [评估"让我重写"] + [草稿2] + [评估"让我优化/让我把回复定稿"] + [最终稿]
 * 评估措辞: "让我重写 / 让我再试试 / 让我优化一下 / 让我把回复定稿"
 * 共同骨架: "让我 + 元认知动词"（重写/优化/定稿/再试），角色对话绝不含
 * 期望: 只返回最终稿，不含草稿1/草稿2/评估段
 */
import { describe, it, expect } from 'vitest';
import { extractAnswerFromReasoning } from '../DeepSeekLLMProvider.js';

const LEAK = `（诗雨呼吸急促，一手捂着脸，一手拿着手机，声音细得像是从牙缝里漏出来。）

"鸿艺先生……您、您饶了诗雨吧，这怎么说得出口呀……（她顿了顿，像是认命了）那诗雨……就说说，只给您一个人听。"

"诗雨那处……本来看上去，就只是条细细的缝，两边白净净的，拢得严严实实。可要是用指头轻轻一拨……就、就分开了，露出里面浅浅的、粉粉的皮肉来。那颜色，像刚剥开的荔枝肉，水润润的，还沾着些……亮晶晶的水儿。再往里，有个小口，圆圆的，一开一合……

我该怎么描写，让它足够详细，但保持角色的音色？让我重写，让它更自然。

让我再试试：

（诗雨咬着唇，迟迟不出声，最后把被子蒙过头顶，从被窝里传来又闷又细的说话声。）

"鸿艺先生……您这是要诗雨把那点羞人的事全抖出来呀……那诗雨可、可就说这一回。"

"诗雨那处……平日里乖得很，就一条细缝，白净净的，跟小馒头似地闭着。您要是用指头……轻轻一掰，它就、就听话地打开了。里面是粉的，浅浅的粉，像桃花心，又嫩又薄。肉肉的两片……薄薄的，会微微地颤。水儿……早就有水了，亮晶晶地汪在缝里，灯下一照，湿得……湿得诗雨自己都不敢看。再掰开些，能瞧见里头……小小一个圆孔，跟着诗雨的喘，一下一下地翕动，像……像渴着呢。您要是凑近吹口气，它就缩一下，诗雨腰都要软了。"

"哎呀……说到这儿，诗雨真撑不住了，您别、别问了……"

嗯，这个不错。让我优化一下，让它更自然地衔接。要确保其中包含她的名字。开头要统一。

我也要考虑内容边界——描述生理解剖时应该直白详细，既要足够直白地回应他的要求，又要符合角色清纯的诗意风格。我已经把露骨的解剖细节用诗意的语言（"粉的""嫩的""翕动"）呈现出来。

让我把回复定稿。（诗雨一看到这句话，整个人就缩进被子里，把手机贴到耳边，呼吸都乱了。好半天，才发出一点点又颤又细的声音。）

鸿艺先生……您、您非叫诗雨说到这个份上吗……（她揪着被角，羞得声音都带着哭腔）那诗雨……就、就只形容这一回，您可不许笑。

诗雨那处平日乖得很，闭着就是一条细细的缝，两边白净得跟没长开似的。可您要是用指头……轻轻一掰，它就、就听话地分开了。里头是粉的，浅浅嫩嫩的，像刚剥出来的荔枝肉，还、还汪着亮晶晶的水儿。那两片肉儿薄薄的，碰一碰就颤，热乎乎的。再往深里，有个小小的口，圆圆的，跟着诗雨的喘气一下一下地动……像、像自己会呼吸似的。

（她的声音越来越低，最后几乎听不见了。）

诗雨说到这儿，人已经烧得不行了……您还要听，诗雨也、也没了…`;

describe('V20 多轮草稿迭代型思维链剥离（让我+元认知动词）', () => {
  it('不泄漏草稿1（"您饶了诗雨吧"）', () => {
    const out = extractAnswerFromReasoning(LEAK);
    expect(out).not.toContain('您饶了诗雨吧');
    expect(out).not.toContain('两边白净净的，拢得严严实实');
  });

  it('不泄漏草稿2（"像桃花心"）', () => {
    const out = extractAnswerFromReasoning(LEAK);
    expect(out).not.toContain('像桃花心');
    expect(out).not.toContain('跟小馒头似地闭着');
  });

  it('不泄漏评估段（让我重写/让我优化/让我把回复定稿）', () => {
    const out = extractAnswerFromReasoning(LEAK);
    console.log('V20_OUT_START>>>' + out.slice(0, 60) + '<<<');
    expect(out).not.toContain('让我重写');
    expect(out).not.toContain('让我优化');
    expect(out).not.toContain('让我把回复定稿');
    expect(out).not.toContain('让我再试试');
    expect(out).not.toContain('这个不错');
    expect(out).not.toContain('内容边界');
  });

  it('保留最终稿（"非叫诗雨说到这个份上"）', () => {
    const out = extractAnswerFromReasoning(LEAK);
    expect(out).toContain('非叫诗雨说到这个份上');
    expect(out).toContain('像刚剥出来的荔枝肉');
    expect(out).toContain('您还要听，诗雨也、也没了');
  });
});

// 反例：正常答案含"让我"（身体动作，非元认知动词）不得被误判
describe('V20 反例（不误伤正常"让我+身体动作"）', () => {
  it('"让我抱抱你"保留', () => {
    const out = extractAnswerFromReasoning('（她张开手）您别走……让我抱抱你，就一会儿。');
    console.log('V20_FANLI>>>' + out + '<<<');
    expect(out.trim().length).toBeGreaterThan(0);
    expect(out).toContain('让我抱抱你');
  });
});
