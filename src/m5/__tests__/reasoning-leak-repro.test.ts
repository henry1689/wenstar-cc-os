    // 模拟流式 stripper 第④步判定条件: extracted.trim()>0 && extracted.length < buf.length-10
    // 流式累积到思维链前缀（含"我现在说话的对象"分析句，无最终稿"梓铭把手机"）
    const sentences = LEAK_CHAIN_V4.split(/(?<=[。！？…\n])/);
