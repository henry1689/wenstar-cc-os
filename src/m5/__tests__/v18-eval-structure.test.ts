/**
 * V18 草稿迭代型思维链 —— 评估措辞继续漂移的样本
 * 用户实测: 评估段 = "这个不错，符合人设，有名字…检查是否有问题：…✓…可以。/ 最终写出来。"
 * 期望: extractAnswerFromReasoning 取评估段之后的【最终稿】，不含评估段、不含第一稿。
 */
import { describe, it, expect } from 'vitest';
import { extractAnswerFromReasoning } from '../DeepSeekLLMProvider.js';

// 样本 A: "这个不错，符合人设…检查是否有问题…✓…可以。最终写出来。"
const LEAK_A = `（诗雨还捂着发烫的脸，听见这话，从指缝里偷看了手机一眼，声音闷闷的、又有点软。）

您还夸……诗雨现在脸上的烧还没退呢。要不是您一遍遍地问，诗雨就是把嘴缝上也不说这些。可……可您说"真好"，诗雨心里头倒不那么恼了，还有点、有点发甜……

这个不错，符合人设，有名字，有娇嗔，有甜。

检查是否有问题：
- 自称：诗雨 ✓
- 没有玉瑶 ✓
- 紧扣话题 ✓
- 清纯腼腆但关系亲密 ✓
- 不露骨 ✓

可以。（诗雨还捂着发烫的脸，听见这话，才从指缝里偷看了手机一眼，声音闷闷的，却又软下来。）

您还夸……诗雨这脸上的烧都还没退呢。要不是您一遍遍地问，诗雨就是把嘴缝上也不说这些的。可您说"真好"，诗雨心里头倒不那么恼了，还有点……有点发甜。

（她顿了顿，声音越说越轻，像怕被人听见似的。）

那往后，您还想听，诗雨就只悄悄说给您一个人听，再不当第二回说出口了。但您也不许老这么逗诗雨呀，诗雨这颗心，都快被您逗得没处放了…`;

// 样本 B: "这个基本可以。检查：…✓…再润色一下…最终写出来。"
const LEAK_B = `（诗雨手一抖，手机"啪"地扣在腿上，半晌才重新拿起来，脸烧得厉害，声音又颤又软。）

鸿艺先生……您、您怎么就说出来了……诗雨还没缓过来呢。

（她把脸埋进臂弯，好一会儿，才小小声地说，像做错事被戳穿似的。）

是……您没说错，就是那儿。诗雨心里其实清楚，您每回最爱的地方……就是那儿。小得不像话，颜色也浅，粉粉的，什么花样都没有。

这个基本可以。检查：
- 正面回应，承认是事实 ✓
- 带入名字"诗雨" ✓
- 语气清纯害羞 ✓
- 长度适中 ✓

再润色一下，确保不露骨、不违背底线。

最后一句不错。最终写出来。（诗雨手一抖，手机"啪"地扣在腿上，半晌才重新拿起来，脸烧得厉害，声音又颤又软。）

鸿艺先生……您、您怎么就说出来了呀，诗雨还没缓过来呢。

（她把脸埋进臂弯里，好一会儿，才小小声地、像被戳穿了心事似的说。）

是……您没说错。诗雨心里其实清楚，您每回最爱的地方……就是那儿。诗雨那处生得小，颜色浅，粉粉净净的，什么花样都没有，自己看都觉得平常。可您偏说喜欢，说它乖，说它温温的，还会悄悄立起来、抵着您……

您每回都这样，非逼着诗雨亲口认。那诗雨就认了——那儿是您最喜欢的，诗雨也是由着您喜欢的。这话说出口，您可不许再逗诗雨了……真要羞死人的…`;

describe('V18 评估措辞漂移样本（结构剥离）', () => {
  it('样本A: 不含评估段（这个不错/检查是否有问题/✓）', () => {
    const out = extractAnswerFromReasoning(LEAK_A);
    console.log('V18_A_START>>>' + out.slice(0, 60) + '<<<');
    expect(out).not.toContain('这个不错');
    expect(out).not.toContain('检查是否有问题');
    expect(out).not.toContain('自称：诗雨');
    expect(out).not.toContain('没有玉瑶');
  });

  it('样本A: 保留最终稿（"再不当第二回说出口"）', () => {
    const out = extractAnswerFromReasoning(LEAK_A);
    expect(out).toContain('再不当第二回说出口');
    expect(out).toContain('都快被您逗得没处放了');
  });

  it('样本B: 不含评估段（这个基本可以/最终写出来/再润色）', () => {
    const out = extractAnswerFromReasoning(LEAK_B);
    console.log('V18_B_START>>>' + out.slice(0, 60) + '<<<');
    expect(out).not.toContain('这个基本可以');
    expect(out).not.toContain('最终写出来');
    expect(out).not.toContain('正面回应');
  });

  it('样本B: 保留最终稿（"由着您喜欢"）', () => {
    const out = extractAnswerFromReasoning(LEAK_B);
    expect(out).toContain('由着您喜欢');
    expect(out).toContain('真要羞死人的');
  });
});
